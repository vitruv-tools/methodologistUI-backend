package tools.vitruv.methodologist.vsum.utilitymethod;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.List;
import org.junit.jupiter.api.Test;
import tools.vitruv.methodologist.vsum.utilitymethod.UtilityMethodClassGenerator.BodyRange;
import tools.vitruv.methodologist.vsum.utilitymethod.UtilityMethodClassGenerator.GeneratedXtend;
import tools.vitruv.methodologist.vsum.utilitymethod.UtilityMethodDefinition.Parameter;

class UtilityMethodClassGeneratorTest {

  private static final String SIMULINK = "tools.vitruv.methodologisttemplate.model.simulink.*";

  private static UtilityMethodDefinition method(String name, String body, String... imports) {
    return new UtilityMethodDefinition(
        name,
        null,
        List.of(new Parameter("model", "SimulinkModel")),
        "List<SubSystem>",
        List.of(imports),
        body);
  }

  @Test
  void generate_writesTheXtendClassWithBodiesVerbatim() {
    UtilityMethodDefinition second =
        new UtilityMethodDefinition(
            "second",
            "Line one\n\nends */ here",
            List.of(),
            "int",
            List.of("java.util.List"),
            "42");
    UtilityMethodDefinition first =
        method("first", "val all = model.eAllContents\nall.filter(SubSystem).toList", SIMULINK);

    GeneratedXtend generated = UtilityMethodClassGenerator.generate(List.of(second, first));

    assertThat(generated.source())
        .isEqualTo(
            """
            package tools.vitruv.methodologisttemplate.consistency.utils

            import java.util.Collection
            import java.util.Map
            import java.util.Set
            import java.util.List
            import tools.vitruv.methodologisttemplate.model.simulink.*

            /**
             * Utility methods generated by the Methodologist Workbench for this project.
             *
             * <p>Use them in reactions and routines after importing
             * {@code tools.vitruv.methodologisttemplate.consistency.utils.Utility}.
             *
             * <p>Do not edit this file: it is regenerated from the utility method
             * definitions on every build.
             */
            final class Utility {

              /**
               * Generated from the utility method {@code first}.
               */
              def static List<SubSystem> first(SimulinkModel model) {
            val all = model.eAllContents
            all.filter(SubSystem).toList
              }

              /**
               * Line one
               *
               * ends *&#47; here
               */
              def static int second() {
            42
              }
            }
            """);
  }

  @Test
  void generate_recordsWhereEveryBodyIs() {
    GeneratedXtend generated =
        UtilityMethodClassGenerator.generate(
            List.of(method("first", "a\nb\nc", SIMULINK), method("second", "d", SIMULINK)));

    List<String> lines = generated.source().lines().toList();
    BodyRange first = generated.bodies().get(0);
    assertThat(first.utilityMethodName()).isEqualTo("first");
    assertThat(lines.get(first.headerLine() - 1)).contains("def static List<SubSystem> first(");
    assertThat(lines.get(first.firstBodyLine() - 1)).isEqualTo("a");
    assertThat(lines.get(first.lastBodyLine() - 1)).isEqualTo("c");
    BodyRange second = generated.bodies().get(1);
    assertThat(lines.get(second.firstBodyLine() - 1)).isEqualTo("d");
    assertThat(second.lastBodyLine()).isEqualTo(second.firstBodyLine());
    assertThat(generated.importLines()).hasSize(1);
    int importLine = generated.importLines().keySet().iterator().next();
    assertThat(lines.get(importLine - 1)).isEqualTo("import " + SIMULINK);
    assertThat(generated.importLines().get(importLine)).containsExactly("first", "second");
  }

  @Test
  void xtendDefinition_showsTheMethodWithIndentedBody() {
    assertThat(UtilityMethodClassGenerator.xtendDefinition(method("first", "a\nb")))
        .isEqualTo("def static List<SubSystem> first(SimulinkModel model) {\n  a\n  b\n}");
  }

  @Test
  void nameProblem_rejectsKeywordsAndInvalidNamesButAllowsTheFormerOclPrefix() {
    assertThat(UtilityMethodClassGenerator.nameProblem("def")).contains("keyword");
    assertThat(UtilityMethodClassGenerator.nameProblem("class")).contains("keyword");
    assertThat(UtilityMethodClassGenerator.nameProblem("1abc")).contains("not a valid");
    assertThat(UtilityMethodClassGenerator.nameProblem(" ")).contains("empty");
    assertThat(UtilityMethodClassGenerator.nameProblem("oclHelper")).isNull();
  }

  @Test
  void signatureProblems_checksParametersTypesImportsAndBody() {
    UtilityMethodDefinition bad =
        new UtilityMethodDefinition(
            "ok",
            null,
            List.of(
                new Parameter("val", "int"), new Parameter("a", "int) {"), new Parameter("a", " ")),
            " ",
            List.of("java..util", "static java.lang.Math.*", "java.util.*"),
            " ");

    assertThat(UtilityMethodClassGenerator.signatureProblems(bad))
        .containsExactly(
            "'val' is not a valid parameter name.",
            "Parameter 'a': 'int) {' is not a type.",
            "The parameter 'a' is declared twice.",
            "Parameter 'a': the type is missing.",
            "Return type: the type is missing.",
            "'java..util' is not a Java import, e.g. 'java.util.List' or 'my.model.*'.",
            "The body must not be empty.");
  }

  @Test
  void signatureProblems_limitsTheBodyLength() {
    UtilityMethodDefinition tooLong =
        method("tooLong", "1".repeat(UtilityMethodClassGenerator.MAX_BODY_LENGTH + 1));

    assertThat(UtilityMethodClassGenerator.signatureProblems(tooLong))
        .containsExactly("The body must not be longer than 20000 characters.");
  }

  @Test
  void isImport_acceptsQualifiedStaticAndWildcardImports() {
    assertThat(UtilityMethodClassGenerator.isImport("java.util.List")).isTrue();
    assertThat(UtilityMethodClassGenerator.isImport("static java.lang.Math.max")).isTrue();
    assertThat(UtilityMethodClassGenerator.isImport("a.b.*")).isTrue();
    assertThat(UtilityMethodClassGenerator.isImport("List")).isFalse();
    assertThat(UtilityMethodClassGenerator.isImport("a.class.B")).isFalse();
    assertThat(UtilityMethodClassGenerator.isImport("a.b;c")).isFalse();
  }
}
