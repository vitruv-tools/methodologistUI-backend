-- Stable versions of a VSUM. A version is a snapshot of the project's build inputs, copied into
-- file_storage rows of their own so that later edits of the working copy cannot change it. The
-- snapshot is built first; version_number stays NULL until that build succeeds and is the next
-- number of the VSUM (1, 2, ...) afterwards. A failed build deletes the snapshot again.
CREATE TABLE vsum_version
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    vsum_id        BIGINT                                  NOT NULL,
    version_number INTEGER,
    created_by_id  BIGINT                                  NOT NULL,
    build_id       BIGINT                                  NOT NULL,
    manifest       JSONB                                   NOT NULL,
    created_at     TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_vsumversion PRIMARY KEY (id),
    CONSTRAINT uq_vsum_version_vsum_number UNIQUE (vsum_id, version_number),
    CONSTRAINT uq_vsum_version_build UNIQUE (build_id)
);

ALTER TABLE vsum_version
    ADD CONSTRAINT FK_VSUMVERSION_ON_VSUM FOREIGN KEY (vsum_id) REFERENCES vsum (id);

ALTER TABLE vsum_version
    ADD CONSTRAINT FK_VSUMVERSION_ON_CREATED_BY FOREIGN KEY (created_by_id) REFERENCES usr (id);

ALTER TABLE vsum_version
    ADD CONSTRAINT FK_VSUMVERSION_ON_BUILD FOREIGN KEY (build_id) REFERENCES vsum_build (id);

-- One publish per VSUM at a time: at most one version without a number.
CREATE UNIQUE INDEX uq_vsum_version_one_pending ON vsum_version (vsum_id) WHERE version_number IS NULL;

-- The copied input files of a version, one table per role, in the order they are sent to the build.
CREATE TABLE vsum_version_ecore
(
    version_id      BIGINT  NOT NULL,
    file_storage_id BIGINT  NOT NULL,
    file_order      INTEGER NOT NULL,
    CONSTRAINT pk_vsum_version_ecore PRIMARY KEY (version_id, file_order),
    CONSTRAINT FK_VSUMVERSIONECORE_ON_VERSION FOREIGN KEY (version_id) REFERENCES vsum_version (id),
    CONSTRAINT FK_VSUMVERSIONECORE_ON_FILE FOREIGN KEY (file_storage_id) REFERENCES file_storage (id)
);

CREATE TABLE vsum_version_reaction
(
    version_id      BIGINT  NOT NULL,
    file_storage_id BIGINT  NOT NULL,
    file_order      INTEGER NOT NULL,
    CONSTRAINT pk_vsum_version_reaction PRIMARY KEY (version_id, file_order),
    CONSTRAINT FK_VSUMVERSIONREACTION_ON_VERSION FOREIGN KEY (version_id) REFERENCES vsum_version (id),
    CONSTRAINT FK_VSUMVERSIONREACTION_ON_FILE FOREIGN KEY (file_storage_id) REFERENCES file_storage (id)
);

CREATE TABLE vsum_version_constraint
(
    version_id      BIGINT  NOT NULL,
    file_storage_id BIGINT  NOT NULL,
    file_order      INTEGER NOT NULL,
    CONSTRAINT pk_vsum_version_constraint PRIMARY KEY (version_id, file_order),
    CONSTRAINT FK_VSUMVERSIONCONSTRAINT_ON_VERSION FOREIGN KEY (version_id) REFERENCES vsum_version (id),
    CONSTRAINT FK_VSUMVERSIONCONSTRAINT_ON_FILE FOREIGN KEY (file_storage_id) REFERENCES file_storage (id)
);

CREATE TABLE vsum_version_view
(
    version_id      BIGINT  NOT NULL,
    file_storage_id BIGINT  NOT NULL,
    file_order      INTEGER NOT NULL,
    CONSTRAINT pk_vsum_version_view PRIMARY KEY (version_id, file_order),
    CONSTRAINT FK_VSUMVERSIONVIEW_ON_VERSION FOREIGN KEY (version_id) REFERENCES vsum_version (id),
    CONSTRAINT FK_VSUMVERSIONVIEW_ON_FILE FOREIGN KEY (file_storage_id) REFERENCES file_storage (id)
);
