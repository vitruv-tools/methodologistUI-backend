CREATE TABLE helper
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    vsum_id     BIGINT                                  NOT NULL,
    name        VARCHAR(255)                            NOT NULL,
    description TEXT,
    return_type VARCHAR(1024)                           NOT NULL,
    body        TEXT                                    NOT NULL,
    imports     TEXT[]                                  NOT NULL DEFAULT '{}',
    created_at  TIMESTAMP WITHOUT TIME ZONE,
    updated_at  TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_helper PRIMARY KEY (id),
    CONSTRAINT uq_helper_vsum_name UNIQUE (vsum_id, name)
);

ALTER TABLE helper
    ADD CONSTRAINT FK_HELPER_ON_VSUM FOREIGN KEY (vsum_id) REFERENCES vsum (id) ON DELETE CASCADE;

CREATE TABLE helper_parameter
(
    helper_id   BIGINT        NOT NULL,
    param_order INTEGER       NOT NULL,
    name        VARCHAR(255)  NOT NULL,
    type        VARCHAR(1024) NOT NULL,
    CONSTRAINT pk_helper_parameter PRIMARY KEY (helper_id, param_order)
);

ALTER TABLE helper_parameter
    ADD CONSTRAINT FK_HELPER_PARAMETER_ON_HELPER FOREIGN KEY (helper_id) REFERENCES helper (id) ON DELETE CASCADE;
