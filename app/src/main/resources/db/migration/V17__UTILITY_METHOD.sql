CREATE TABLE utility_method
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    vsum_id     BIGINT                                  NOT NULL,
    name        VARCHAR(255)                            NOT NULL,
    description TEXT,
    return_type VARCHAR(1024)                           NOT NULL,
    body        TEXT                                    NOT NULL,
    imports     TEXT[]                                  NOT NULL DEFAULT '{}',
    created_at  TIMESTAMP WITHOUT TIME ZONE,
    updated_at  TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_utility_method PRIMARY KEY (id),
    CONSTRAINT uq_utility_method_vsum_name UNIQUE (vsum_id, name)
);

ALTER TABLE utility_method
    ADD CONSTRAINT FK_UTILITY_METHOD_ON_VSUM FOREIGN KEY (vsum_id) REFERENCES vsum (id) ON DELETE CASCADE;

CREATE TABLE utility_method_parameter
(
    utility_method_id BIGINT        NOT NULL,
    param_order       INTEGER       NOT NULL,
    name              VARCHAR(255)  NOT NULL,
    type              VARCHAR(1024) NOT NULL,
    CONSTRAINT pk_utility_method_parameter PRIMARY KEY (utility_method_id, param_order)
);

ALTER TABLE utility_method_parameter
    ADD CONSTRAINT FK_UTILITY_METHOD_PARAMETER_ON_UTILITY_METHOD FOREIGN KEY (utility_method_id) REFERENCES utility_method (id) ON DELETE CASCADE;
